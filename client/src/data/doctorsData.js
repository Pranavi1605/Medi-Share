export const getAvailableDoctors = () => {
  const stored = JSON.parse(localStorage.getItem("registeredDoctors")) || [];
  const merged = [...stored];

  VERIFIED_SPECIALISTS.forEach(vs => {
    if (!merged.some(d => d.name?.toLowerCase().trim() === vs.name.toLowerCase().trim())) {
      merged.push(vs);
    }
  });

  return merged;
};

export const addNewDoctor = (newDoc) => {
  if (!newDoc || !newDoc.name) return false;
  const current = getAvailableDoctors();
  const exists = current.some(d => d.name.toLowerCase().trim() === newDoc.name.toLowerCase().trim());
  if (exists) return false;

  const docEmail = newDoc.email || `${newDoc.name.toLowerCase().replace(/[^a-z]/g, "")}@gmail.com`;

  const docToAdd = {
    ...newDoc,
    email: docEmail,
    doctorId: newDoc.doctorId || `DOC-USER-${Date.now().toString().slice(-4)}`,
    avatar: newDoc.avatar || "👨‍⚕️",
    experience: newDoc.experience || "10 years"
  };

  const updated = [docToAdd, ...current];
  localStorage.setItem("registeredDoctors", JSON.stringify(updated));
  window.dispatchEvent(new Event("dashboardUpdate"));
  return true;
};
